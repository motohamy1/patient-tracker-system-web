// neon/port-baseline.mjs — generates neon/migrations/0000_baseline.sql from
// supabase/migrations/*.sql. Run: `npm run db:port`. No DATABASE_URL needed.
//
// Port rules (Supabase platform -> Neon Managed Auth + Object Storage):
//   auth.users            -> neon_auth."user" (Managed Better Auth, uuid ids)
//   auth.uid()            -> public.app_uid() (uuid; reads SET LOCAL app.user_id)
//   extensions.digest(    -> public.digest( (pgcrypto, search_path='' safe)
//   TO anon/authenticated/service_role -> TO public (single-owner connection)
//   storage.* statements  -> dropped (Neon Object Storage `uploads` bucket;
//     access enforced in app via assertDocumentPath + workspace resolution)
// Posture change: the app connects as table owner, so RLS policies are inert
// documentation; enforcement is app-layer org filters + trigger guards
// (provenance/audit/patient-self), all preserved by this port.
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "supabase", "migrations");
const outDir = join(root, "neon", "migrations");
const outFile = join(outDir, "0000_baseline.sql");

const PREAMBLE = `-- 0000_baseline.sql — GENERATED by neon/port-baseline.mjs. Do not hand-edit.
-- Regenerate: npm run db:port. Requires Managed Auth deployed first
-- (neon_auth."user" must exist for the FK references below).

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Session identity for triggers/guards (replaces auth.uid()).
CREATE OR REPLACE FUNCTION public.app_uid() RETURNS uuid
LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('app.user_id', true), '')::uuid $$;
`;

function portFile(name, sql) {
  const out = sql
    .replace(/create policy\b[^;]*?on\s+storage\.[^;]*?;/gis, "-- NEON-PORT: dropped Supabase storage policy (Neon Object Storage `uploads` bucket; enforced in app).\n")
    .replace(/insert\s+into\s+storage\.[^;]*?;/gis, "-- NEON-PORT: dropped storage bucket seed.\n")
    .replace(/extensions\.digest\(/g, "public.digest(")
    .replace(/auth\.users/g, 'neon_auth."user"')
    .replace(/auth\.uid\(\)/g, "public.app_uid()")
    .replace(/\bservice_role\b/gi, "public")
    .replace(/\banon\b/gi, "public")
    .replace(/\bauthenticated\b/gi, "public")
    .replace(/public(\s*,\s*public)+/g, "public");
  return `\n-- ── source: supabase/migrations/${name} ──\n${out}\n`;
}

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
let body = "";
const tables = new Set();
for (const f of files) {
  const sql = readFileSync(join(srcDir, f), "utf8");
  const ported = portFile(f, sql);
  for (const m of ported.matchAll(/create table public\.("?)(\w+)\1/gi)) tables.add(m[2]);
  body += ported;
}

const POSTAMBLE = `\n-- NEON-PORT: ${tables.size} app tables ported (${files.length} sources).\n-- RLS policies above are inert for the table owner; enforcement is app-layer\n-- org filters (resolveWorkspaceRole) + trigger guards. See neon/README.md.\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, PREAMBLE + body + POSTAMBLE);
console.log(`wrote ${outFile} (${files.length} sources, ${tables.size} tables)`);
